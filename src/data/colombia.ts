export function getDepartment(key: string): Department | undefined {
  return DEPARTMENTS.find((d) => d.key === key);
}

export function getDepartmentLabel(key: string): string {
  return getDepartment(key)?.label ?? key;
}

export function getMunicipalityLabel(
  departmentKey: string,
  municipalityKey: string
): string {
  const dept = getDepartment(departmentKey);
  return (
    dept?.municipalities.find((m) => m.key === municipalityKey)?.label ??
    municipalityKey
  );
}
